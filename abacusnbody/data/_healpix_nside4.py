"""
The 192 Nside=4 NEST HEALPix pixel-center unit vectors.

Abacus stores the *direction* of a MAP's velocity relative to the mean local dark
matter as an Nside=4 NEST HEALPix pixel index -- 192 pixels, so one byte. This
table inverts that index. It appears as ``rel_vel_healpix`` in both
:mod:`abacusnbody.data.output_particle` and :mod:`abacusnbody.data.maplog`, each
of which re-exports ``rel_vel_healpix_lookup`` from here.

Abacus also writes this exact table into every ASDF header as the
``rel_vel_healpix_lookup`` ndarray, so data files are self-describing and a reader
needs no HEALPix library. The copy here is a convenience for code that has no file
open; ``tests/test_aurora_readers.py`` asserts the two agree.

Generated from ``abacus/src/include/healpix_nside4_nest.h``, which is itself
verified against the ``vec2pix_nest64()`` that produces the indices
(``abacus/tests/test_healpix_nside4.cpp``). Do not hand-edit.
"""

